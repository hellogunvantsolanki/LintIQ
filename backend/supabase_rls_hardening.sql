-- LintIQ Supabase Schema & RLS Hardening
-- 1. Lock user_profiles to read-only (SELECT) for anon & authenticated clients.
-- 2. Create ai_problems & user_seen_ai_problems tables if missing (fixes 404 Not Found).

-- ─── 1. USER_PROFILES RLS HARDENING ───────────────────────────────────────────
ALTER TABLE public.user_profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Enable insert for authenticated users only" ON public.user_profiles;
DROP POLICY IF EXISTS "Enable update for users based on id" ON public.user_profiles;
DROP POLICY IF EXISTS "Users can insert own profile" ON public.user_profiles;
DROP POLICY IF EXISTS "Users can update own profile" ON public.user_profiles;
DROP POLICY IF EXISTS "Allow public read access" ON public.user_profiles;
DROP POLICY IF EXISTS "Public read access for leaderboard" ON public.user_profiles;

CREATE POLICY "Public read access for leaderboard"
  ON public.user_profiles
  FOR SELECT
  TO anon, authenticated
  USING (true);

REVOKE INSERT, UPDATE, DELETE ON public.user_profiles FROM anon, authenticated;
GRANT SELECT ON public.user_profiles TO anon, authenticated;

-- ─── 2. AI_PROBLEMS SHARED POOL TABLE ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.ai_problems (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100001) PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  difficulty TEXT NOT NULL DEFAULT 'Medium',
  category TEXT NOT NULL DEFAULT 'Algorithms',
  tags JSONB NOT NULL DEFAULT '[]'::jsonb,
  language TEXT NOT NULL DEFAULT 'python',
  buggy_code TEXT NOT NULL,
  test_cases JSONB NOT NULL DEFAULT '[]'::jsonb,
  hint TEXT NOT NULL DEFAULT 'Inspect edge cases and loop bounds.',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ai_problems_cat_diff ON public.ai_problems (category, difficulty);

ALTER TABLE public.ai_problems ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read access for ai_problems" ON public.ai_problems;
CREATE POLICY "Public read access for ai_problems"
  ON public.ai_problems
  FOR SELECT
  TO anon, authenticated
  USING (true);

REVOKE INSERT, UPDATE, DELETE ON public.ai_problems FROM anon, authenticated;
GRANT SELECT ON public.ai_problems TO anon, authenticated;

-- ─── 3. USER_SEEN_AI_PROBLEMS TRACKER ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.user_seen_ai_problems (
  user_id UUID NOT NULL,
  problem_id BIGINT NOT NULL,
  seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, problem_id)
);

ALTER TABLE public.user_seen_ai_problems ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users manage own seen ai problems" ON public.user_seen_ai_problems;
CREATE POLICY "Users manage own seen ai problems"
  ON public.user_seen_ai_problems
  FOR ALL
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);
